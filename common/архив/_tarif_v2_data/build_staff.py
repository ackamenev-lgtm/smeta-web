# ставки по специальностям
specs = {}
for row in r3.iter_rows(min_row=6, max_row=26, values_only=True):
    code = row[0]
    if not code:
        continue
    specs[code] = dict(name=row[1], what=row[2], bs=row[3] or 0, bm=row[4] or 0, hire=row[5],
                       ms=row[8], mm=row[9], cs=row[12], cm=row[13])

