norm = {}
for row in r2.iter_rows(min_row=6, values_only=True):
    if row[0] and row[3]:
        norm[row[0]] = dict(n=row[5], how=row[16])

rows = []   # ("sec", title) | ("item", dict)
for row in r1.iter_rows(min_row=5, values_only=True):
    a = row[0]
    if a is None:
        continue
    if row[1] is None and row[2] is None:
        rows.append(("sec", a)); continue
    x = dict(art=a, name=row[1], unit=row[2], new=row[3] == "да", spec=row[4],
             mkt_s=row[5], mkt_m=row[6], p_s=row[7], p_m=row[8], up_s=row[9], up_m=row[10],
             b_s=row[11], b_m=row[12])
    x.update(norm.get(a, {}))
    rows.append(("item", x))
items = [x for k, x in rows if k == "item"]
log.write(f"items {len(items)}; none price {sum(1 for x in items if x['p_s'] is None)}\n")

